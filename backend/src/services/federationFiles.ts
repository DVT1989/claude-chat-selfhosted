/**
 * Federation kinds "files" and "profile" (moving house).
 *
 * - files: text files from the user's workspace (/workspace/<id>), the admin-chat workspace (/workspace/_admin-<id>, admins)
 *   and home (/claude-homes/user-<id>), one item per file. Left out: everything hidden (starts with a dot: .ssh, .env,
 *   .claude.json, .memory.token ...), secret-looking names (token, key, pem, password, credential ...), files with a private
 *   key or a secret-looking line inside, binaries, big or generated folders (node_modules, .git, caches, projects, attachments ...)
 *   and the generated CLAUDE.md. Limits: per file, per user and per page (see MAX_*).
 * - profile: name and avatar (data URL) of a user. Matched on e-mail; a user that does not exist here is skipped.
 * Conflicts (different content here and there) are never overwritten: they go to federation_conflicts like other kinds.
 */
import { existsSync, lstatSync, mkdirSync, readdirSync, readFileSync, openSync, readSync, closeSync, writeFileSync, utimesSync, chownSync, statSync } from 'fs';
import { join, dirname, resolve, sep } from 'path';
import { query } from '../db';
import { config } from '../config';
import type { Kind, RawItem, ApplyCtx } from './federation';

const MAX_FILE = 512 * 1024;
const MAX_USER_TOTAL = 20 * 1024 * 1024;
const MAX_USER_FILES = 1500;
const MAX_DEPTH = 8;
const UID = 1001;
const GID = 1001;

const SKIP_DIRS = new Set([
  'node_modules', '.git', '.cache', '__pycache__', '.venv', 'venv', 'env', 'dist', 'build', '.next', 'target', 'vendor', 'coverage', 'tmp', 'temp',
  'attachments', 'projects', 'site-packages', 'Library', 'AppData', 'Downloads', 'snap',
]);
const SECRET_NAME = /(?:^|[._-])(?:token|tokens|key|keys|secret|secrets|password|passwd|pass|credential|credentials|cred|creds|private|id_rsa|id_ed25519|id_ecdsa|htpasswd|netrc|pgpass|sudo)(?:[._-]|$)|\.(?:pem|key|p12|pfx|crt|cer|kdbx|keystore|jks|ppk|gpg|asc|token|pass|env|sqlite|db|log)$|^\.env|^credentials|^secrets?\./i;
const BINARY_EXT = /\.(?:png|jpe?g|gif|webp|ico|bmp|tiff?|pdf|zip|gz|tgz|bz2|xz|7z|rar|tar|exe|dll|so|dylib|bin|dmg|iso|mp[34]|mov|avi|mkv|wav|flac|woff2?|ttf|otf|eot|class|jar|pyc|o|a|docx?|xlsx?|pptx?|msi|apk|wasm|lock)$/i;
const BAK = /\.bak(?:-|$)|~$|\.orig$|\.swp$/i;
const SECRET_CONTENT = /-----BEGIN [A-Z0-9 ]*PRIVATE KEY|\b(?:sk-ant-[A-Za-z0-9_-]{20,}|gh[pousr]_[A-Za-z0-9]{30,}|github_pat_[A-Za-z0-9_]{30,}|AKIA[0-9A-Z]{16}|xox[abprs]-[A-Za-z0-9-]{20,})\b/;

export const homeDir = (userId: string) => join(config.claudeHomesRoot, `user-${userId}`);
const roots = (userId: string, admin: boolean): Array<{ name: string; dir: string }> => [
  { name: 'ws', dir: join(config.workspaceRoot, userId) },
  ...(admin ? [{ name: 'adm', dir: join(config.workspaceRoot, `_admin-${userId}`) }] : []),
  { name: 'home', dir: homeDir(userId) },
];

/** True when this relative path may never travel (also checked on arrival). */
export function isExcludedPath(rel: string): boolean {
  const parts = rel.split('/');
  if (!rel || parts.length > MAX_DEPTH + 1) return true;
  for (let i = 0; i < parts.length; i++) {
    const p = parts[i];
    if (!p || p === '.' || p === '..' || p.startsWith('.')) return true;
    if (i < parts.length - 1 && SKIP_DIRS.has(p)) return true;
  }
  const f = parts[parts.length - 1];
  if (SECRET_NAME.test(f) || BINARY_EXT.test(f) || BAK.test(f)) return true;
  if (parts.length === 1 && /^(?:CLAUDE|AGENTS)\.md$/i.test(f)) return true; // generated by the app on every run
  return false;
}

function looksBinary(buf: Buffer): boolean {
  const n = Math.min(buf.length, 4096);
  for (let i = 0; i < n; i++) if (buf[i] === 0) return true;
  return false;
}

interface Meta { id: string; ts: string; ownerId: string; root: string; rel: string; abs: string; size: number }

function scanUser(userId: string, admin: boolean): Meta[] {
  const out: Meta[] = [];
  let total = 0;
  for (const r of roots(userId, admin)) {
    if (!existsSync(r.dir)) continue;
    const walk = (rel: string, depth: number) => {
      if (depth > MAX_DEPTH || out.length >= MAX_USER_FILES) return;
      let names: string[];
      try { names = readdirSync(join(r.dir, rel)); } catch { return; }
      for (const e of names.sort()) {
        if (e.startsWith('.')) continue;
        const relE = rel ? `${rel}/${e}` : e;
        const abs = join(r.dir, relE);
        let st;
        try { st = lstatSync(abs); } catch { continue; }
        if (st.isSymbolicLink()) continue;
        if (st.isDirectory()) { if (!SKIP_DIRS.has(e)) walk(relE, depth + 1); continue; }
        if (!st.isFile() || st.size > MAX_FILE || st.size === 0 || isExcludedPath(relE)) continue;
        if (out.length >= MAX_USER_FILES || total + st.size > MAX_USER_TOTAL) continue;
        total += st.size;
        out.push({ id: `${userId}/${r.name}/${relE}`, ts: new Date(st.mtimeMs).toISOString(), ownerId: userId, root: r.name, rel: relE, abs, size: st.size });
      }
    };
    walk('', 0);
  }
  return out;
}

async function users(): Promise<Array<{ id: string; email: string; admin: boolean }>> {
  return (await query<{ id: string; email: string; role: string }>('SELECT id::text, email, role FROM users WHERE is_active')).rows.map((u) => ({ id: u.id, email: u.email, admin: u.role === 'admin' }));
}

/** Reads one file for export; null when it turns out to be binary or secret after all. */
function readItem(m: Meta, email: string): RawItem | null {
  let buf: Buffer;
  try { buf = readFileSync(m.abs); } catch { return null; }
  if (buf.length > MAX_FILE || looksBinary(buf)) return null;
  if (SECRET_CONTENT.test(buf.toString('utf8'))) return null;
  return { id: m.id, ts: m.ts, owner_email: email, data: { root: m.root, path: m.rel, b64: buf.toString('base64') } };
}

async function metas(owner?: string): Promise<Array<Meta & { email: string }>> {
  const all: Array<Meta & { email: string }> = [];
  for (const u of await users()) {
    if (owner && u.email.toLowerCase() !== owner.toLowerCase()) continue;
    for (const m of scanUser(u.id, u.admin)) all.push({ ...m, email: u.email });
  }
  return all.sort((a, b) => (a.ts === b.ts ? a.id.localeCompare(b.id) : a.ts.localeCompare(b.ts)));
}

function targetPath(owner: string, d: { root: string; path: string }): string {
  const rel = String(d.path ?? '');
  if (!['ws', 'adm', 'home'].includes(d.root) || isExcludedPath(rel)) throw new Error(`Pad niet toegestaan: ${rel.slice(0, 80)}`);
  const base = d.root === 'ws' ? join(config.workspaceRoot, owner) : d.root === 'adm' ? join(config.workspaceRoot, `_admin-${owner}`) : homeDir(owner);
  const abs = resolve(base, rel);
  if (!abs.startsWith(resolve(base) + sep)) throw new Error('Ongeldig pad');
  return abs;
}

function writeFileSafe(owner: string, d: { root: string; path: string; b64: string }, ts: string): void {
  const abs = targetPath(owner, d);
  const buf = Buffer.from(String(d.b64 ?? ''), 'base64');
  if (buf.length > MAX_FILE) throw new Error('Bestand te groot');
  if (looksBinary(buf) || SECRET_CONTENT.test(buf.toString('utf8'))) throw new Error('Bestand niet toegestaan (binair of geheim)');
  // no write through a symlink anywhere below the base directory
  const baseDir = resolve(abs.slice(0, abs.length - String(d.path).length - 1));
  let cur = baseDir;
  for (const part of String(d.path).split('/')) {
    cur = join(cur, part);
    if (existsSync(cur) && lstatSync(cur).isSymbolicLink()) throw new Error('Pad bevat een symlink');
  }
  const dirs: string[] = [];
  for (let p = dirname(abs); !existsSync(p) && p.length > 1; p = dirname(p)) dirs.push(p);
  mkdirSync(dirname(abs), { recursive: true });
  for (const p of dirs) try { chownSync(p, UID, GID); } catch { /* ignore */ }
  writeFileSync(abs, buf, { mode: 0o644 });
  try { chownSync(abs, UID, GID); } catch { /* ignore */ }
  const t = new Date(ts);
  if (!Number.isNaN(t.getTime())) try { utimesSync(abs, t, t); } catch { /* ignore */ }
}

export const filesKind: Kind = {
  ownerOnly: true,
  async list(after, limit, owner) {
    let all = await metas(owner);
    if (after) all = all.filter((i) => i.ts > after[0] || (i.ts === after[0] && i.id > after[1]));
    const out: RawItem[] = [];
    for (const m of all) {
      if (out.length >= limit) break;
      const it = readItem(m, m.email);
      if (it) out.push(it);
    }
    return out;
  },
  async one(localId) {
    const [uid, root, ...rest] = localId.split('/');
    const u = (await users()).find((x) => x.id === uid);
    if (!u || !rest.length) return null;
    const m = scanUser(u.id, u.admin).find((x) => x.id === `${uid}/${root}/${rest.join('/')}`);
    return m ? readItem(m, u.email) : null;
  },
  async count() { const a = await metas(); return { count: a.length, latest: a.length ? a[a.length - 1].ts : null }; },
  async ownerOf(localId) { return localId.split('/')[0] ?? null; },
  name: (d) => `${d.root}/${d.path}`,
  natural: 'conflict',
  async find(owner, d) {
    let abs: string;
    try { abs = targetPath(owner, d); } catch { return null; }
    try { return existsSync(abs) && statSync(abs).isFile() ? `${owner}/${d.root}/${d.path}` : null; } catch { return null; }
  },
  async create(owner, d, c: ApplyCtx) { writeFileSafe(owner, d, c.ts); return `${owner}/${d.root}/${d.path}`; },
  async update(id, d, c: ApplyCtx) { writeFileSafe(id.split('/')[0], d, c.ts); },
};

export const profileKind: Kind = {
  ownerOnly: true,
  async list(after, limit, owner) {
    const params: unknown[] = [after?.[0] ?? '-infinity', after?.[1] ?? '00000000-0000-0000-0000-000000000000', limit];
    let w = `(u.updated_at, u.id) > ($1::timestamptz, $2::uuid) AND u.is_active`;
    if (owner) { params.push(owner); w += ' AND lower(u.email) = lower($4)'; }
    const r = await query(`SELECT u.id::text AS id, to_char(u.updated_at AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.US"Z"') AS ts, u.email, u.name, u.avatar
      FROM users u WHERE ${w} ORDER BY u.updated_at, u.id LIMIT $3`, params);
    return r.rows.filter((u) => !u.avatar || String(u.avatar).length < 2_000_000)
      .map((u) => ({ id: u.id, ts: u.ts, owner_email: u.email, data: { name: u.name ?? '', avatar: u.avatar ?? null } }));
  },
  async one(localId) {
    const u = (await query(`SELECT id::text AS id, to_char(updated_at AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.US"Z"') AS ts, email, name, avatar FROM users WHERE id = $1::uuid`, [localId])).rows[0];
    return u ? { id: u.id, ts: u.ts, owner_email: u.email, data: { name: u.name ?? '', avatar: u.avatar ?? null } } : null;
  },
  async count() {
    const r = await query<{ n: string; latest: string | null }>(`SELECT count(*) AS n, to_char(max(updated_at) AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.US"Z"') AS latest FROM users WHERE is_active`);
    return { count: Number(r.rows[0].n), latest: r.rows[0].latest };
  },
  async ownerOf(localId) { return localId; },
  name: (d) => `Profiel ${d.name || ''}`.trim(),
  natural: 'conflict',
  // the profile belongs to the user with the same e-mail: it always exists, so compare instead of create
  async find(owner) { return owner; },
  async create(owner, d) { await applyProfile(owner, d); return owner; },
  async update(id, d) { await applyProfile(id, d); },
};

async function applyProfile(userId: string, d: { name?: string; avatar?: string | null }): Promise<void> {
  const avatar = typeof d.avatar === 'string' && /^data:image\/(?:png|jpe?g|gif|webp);base64,[A-Za-z0-9+/=]+$/.test(d.avatar) && d.avatar.length < 2_000_000 ? d.avatar : null;
  const name = String(d.name ?? '').trim().slice(0, 100);
  await query('UPDATE users SET name = COALESCE(NULLIF($2, \'\'), name), avatar = $3, updated_at = now() WHERE id = $1', [userId, name, avatar]);
}
